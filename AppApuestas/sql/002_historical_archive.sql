-- AppApuestas historical archive foundation.
-- Run after 001_research_snapshots.sql.
-- This migration creates the archive schema. Historical rows are imported separately.
-- All public tables remain backend-only; never grant anon/authenticated access.

create table if not exists public.historical_matches (
    id bigint generated by default as identity primary key,
    source text not null,
    source_match_key text not null,
    competition_code text,
    competition_name text,
    country text,
    season text not null,
    match_date date not null,
    kickoff_time text,
    home_team text not null,
    away_team text not null,
    home_goals integer not null,
    away_goals integer not null,
    ht_home_goals integer,
    ht_away_goals integer,
    result_1x2 text not null,
    stats jsonb not null default '{}'::jsonb,
    source_url text,
    ingested_at timestamptz not null default now(),
    constraint historical_matches_source_key unique (source, source_match_key)
);

create table if not exists public.market_odds_summary (
    id bigint generated by default as identity primary key,
    event_id text not null,
    sport text not null,
    league text,
    home_team text,
    away_team text,
    market_key text not null,
    selection text not null,
    line numeric,
    bookmaker text not null,
    provider text not null,
    snapshot_phase text not null default 'periodic',
    opening_odds numeric,
    closing_odds numeric,
    min_odds numeric,
    max_odds numeric,
    average_odds numeric,
    opening_implied_probability numeric,
    closing_implied_probability numeric,
    opening_fair_probability numeric,
    closing_fair_probability numeric,
    average_overround numeric,
    closing_clv_probability_pp numeric,
    closing_price_dislocation_pct numeric,
    first_observed_at timestamptz not null,
    last_observed_at timestamptz not null,
    kickoff_utc timestamptz,
    seconds_from_kickoff_min integer,
    seconds_from_kickoff_max integer,
    is_closing_line boolean not null default false,
    is_closing_snapshot boolean not null default false,
    snapshot_count integer not null
);

create table if not exists public.historical_match_features (
    id bigint generated by default as identity primary key,
    source text not null,
    source_license text,
    source_match_id text not null,
    competition_name text,
    season_name text,
    match_date date not null,
    home_team text not null,
    away_team text not null,
    home_score integer,
    away_score integer,
    home_xg numeric,
    away_xg numeric,
    home_shots integer,
    away_shots integer,
    home_big_chances integer,
    away_big_chances integer,
    home_shots_on_target integer,
    away_shots_on_target integer,
    home_corners integer,
    away_corners integer,
    home_yellow_cards integer,
    away_yellow_cards integer,
    home_red_cards integer,
    away_red_cards integer,
    home_passes integer,
    away_passes integer,
    home_completed_passes integer,
    away_completed_passes integer,
    home_pressures integer,
    away_pressures integer,
    ingested_at timestamptz,
    constraint historical_match_features_source_key unique (source, source_match_id)
);

create table if not exists public.team_identity_map (
    provider text not null,
    provider_team_id text not null,
    canonical_team_name text not null,
    provider_team_name text,
    source_event_id text,
    confidence numeric not null check (confidence >= 0 and confidence <= 1),
    metadata jsonb not null default '{}'::jsonb,
    verified_at timestamptz,
    updated_at timestamptz,
    primary key (provider, provider_team_id)
);

create table if not exists public.event_identity_aliases (
    alias_event_id text primary key,
    canonical_event_id text not null,
    sport text,
    reason text,
    confidence numeric not null check (confidence >= 0 and confidence <= 1),
    created_at timestamptz,
    updated_at timestamptz
);

comment on table public.historical_matches is
    'Historical football and MLB results with source attribution and optional match stats.';
comment on table public.market_odds_summary is
    'Compacted market history: opening/closing prices, ranges and observation counts; not tick-by-tick.';
comment on table public.historical_match_features is
    'Attributed advanced match features. Missing values remain NULL and raw provider payloads are not stored.';
comment on table public.team_identity_map is
    'High-confidence provider team IDs linked to canonical team names.';
comment on table public.event_identity_aliases is
    'High-confidence event ID aliases used to reconcile the same event across providers.';

create index if not exists historical_matches_home_date_idx
    on public.historical_matches (home_team, match_date desc);
create index if not exists historical_matches_away_date_idx
    on public.historical_matches (away_team, match_date desc);
create index if not exists historical_matches_date_idx
    on public.historical_matches (match_date desc);
create index if not exists historical_match_features_team_date_idx
    on public.historical_match_features (home_team, match_date desc);
create index if not exists historical_match_features_away_date_idx
    on public.historical_match_features (away_team, match_date desc);
create index if not exists historical_match_features_xg_date_idx
    on public.historical_match_features (match_date desc)
    where home_xg is not null and away_xg is not null;
create index if not exists market_odds_summary_event_idx
    on public.market_odds_summary (event_id, market_key, bookmaker);
create index if not exists market_odds_summary_sport_date_idx
    on public.market_odds_summary (sport, last_observed_at desc);
create index if not exists team_identity_map_canonical_idx
    on public.team_identity_map (canonical_team_name);

alter table public.historical_matches enable row level security;
alter table public.market_odds_summary enable row level security;
alter table public.historical_match_features enable row level security;
alter table public.team_identity_map enable row level security;
alter table public.event_identity_aliases enable row level security;

revoke all on table public.historical_matches from anon, authenticated;
revoke all on table public.market_odds_summary from anon, authenticated;
revoke all on table public.historical_match_features from anon, authenticated;
revoke all on table public.team_identity_map from anon, authenticated;
revoke all on table public.event_identity_aliases from anon, authenticated;

grant select, insert, update, delete on table public.historical_matches to service_role;
grant select, insert, update, delete on table public.market_odds_summary to service_role;
grant select, insert, update, delete on table public.historical_match_features to service_role;
grant select, insert, update, delete on table public.team_identity_map to service_role;
grant select, insert, update, delete on table public.event_identity_aliases to service_role;
grant usage, select on all sequences in schema public to service_role;
